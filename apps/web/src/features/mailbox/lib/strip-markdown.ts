// 목록 한 줄 미리보기용 — 마크다운 기호를 벗겨 평문으로 만든다. 렌더가 아니라 요약이라 정확한 파싱은 필요 없다
export const stripMarkdown = (text: string) =>
  text
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1') // 이미지 → 설명
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1') // 링크 → 글자
    .replace(/^\s*(#{1,6}\s+|>\s?|[-*+]\s+(\[[ xX]\]\s+)?)/gm, '') // 제목·인용·불릿·체크박스
    .replace(/^\s*\|?\s*(:?-{3,}:?\s*\|?\s*)+$/gm, '') // 표 머리 구분 줄·구분선
    .replace(/\|/g, ' ') // 표 세로줄
    .replace(/\*\*|\*|~~|`|__/g, '') // 굵게·기울임·취소선·코드
    .replace(/\s+/g, ' ')
    .trim();
